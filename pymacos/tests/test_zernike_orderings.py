class Probe:
    def __init__(self, work):
        self.work, self.ztype = work, None
        m.init(128)

    def load(self, ztype):
        if ztype == self.ztype:
            return True
        for n in (66, 37):
            p = self.work / 'z.in'
            p.write_text(DECK.format(ztype=ztype, n=n))
            try:
                m.load(str(p))
            except Exception:
                continue
            m.ray_hist('on')
            self.ztype = ztype
            return True
        self.ztype = None
        return False

    def sag(self, ztype, k):
        """(R, A, sag / COEF) for a unit coefficient in mode k."""
        assert self.load(ztype), f'{ztype} did not load'
        m.setEltSrfZernCoef(1, [k], [COEF], reset=True)
        m.modify()
        _, nrays, _ = m.trace_rays(2)
        h = m.ray_pos_hist(int(nrays))
        ok = h['ok'][:, 1]
        x, y, z = h['P'][0, ok, 1], h['P'][1, ok, 1], h['P'][2, ok, 1]
        assert ok.sum() > 300
        return np.hypot(x, y), np.arctan2(y, x), z / COEF


