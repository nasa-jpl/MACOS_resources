def poly_eval(text, R, A):
    """Evaluate a printed polynomial ('(3R^3^ - 2R) sin(A)') at (R, A)."""
    t = re.sub(r'\^(\d+)\^', r'**\1', text)
    t = re.sub(r'(\d)R', r'\1*R', t)
    t = re.sub(r'\) (sin|cos)', r')*\1', t)
    t = re.sub(r'(R(?:\*\*\d+)?) (sin|cos)', r'\1*\2', t)
    t = re.sub(r'\((\d*)A\)', lambda g: f"({g.group(1) or 1}*A)", t)
    return eval(t, {'R': R, 'A': A, 'sin': np.sin, 'cos': np.cos})


def read_table():
    rows = []
    lines = TABLE.read_text().splitlines()
    head = next(i for i, ln in enumerate(lines) if ln.startswith('| n | m |'))
    cols = [c.strip() for c in lines[head].strip('|').split('|')]
    for ln in lines[head + 2:]:
        if not ln.startswith('|'):
            break
        cells = dict(zip(cols, [c.strip() for c in ln.strip('|').split('|')]))
        rows.append({'n': int(cells['n']), 'm': int(cells['m']), 'poly': cells['Polynomial'],
                     **{c: (int(cells[c]) if cells[c].isdigit() else None) for c in COLUMNS}})
    return rows, TABLE.read_text()


