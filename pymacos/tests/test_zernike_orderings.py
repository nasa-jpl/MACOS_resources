def test_must_fail_altered_rows_are_refused(probe, table):
    rows, _ = table
    r = next(r for r in rows if (r['n'], r['m']) == (3, 1))           # coma, cos
    swapped = dict(r, poly=r['poly'].replace('cos', 'sin'))
    assert mismatches(probe, [swapped], 'ANSI', 'ANSI'), 'sin for cos must fail'
    wrong = dict(r, ANSI=r['ANSI'] + 1)
    assert mismatches(probe, [wrong], 'ANSI', 'ANSI'), 'a wrong index must fail'
    unnorm = dict(r)
    assert mismatches(probe, [unnorm], 'NormANSI', 'ANSI'), 'NormANSI without its factor must fail'


def textbook_noll():
    j, out = 1, {}
    for n in range(0, 11):
        for am in range(n % 2, n + 1, 2):
            if am == 0:
                out[(n, 0)] = j
                j += 1
            else:
                for _ in range(2):
                    out[(n, am if j % 2 == 0 else -am)] = j    # Noll: even j -> cos, odd j -> sin
                    j += 1
    return out


def textbook_fringe(n, mm):
    s = (n + abs(mm)) // 2
    return s * s + 1 + 2 * (s - abs(mm)) + (1 if mm < 0 else 0)


def test_indices_follow_the_textbook_orderings(table):
    rows, _ = table
    noll = textbook_noll()
    for r in rows:
        n, mm = r['n'], r['m']
        if n <= 10:
            assert r['ANSI'] == (n * (n + 2) + mm) // 2 + 1, r
            assert r['Born & Wolf'] == n * (n + 1) // 2 + 1 + (n - mm) // 2, r
            assert r['Noll'] == noll[(n, mm)], r
        f = textbook_fringe(n, mm)
        assert r['Fringe'] == (37 if (n, mm) == (12, 0) else (f if f <= 36 else None)), r
        assert r['Ext. Fringe'] in (f, None), r


def test_against_the_3_2_table(table):
    rows, _ = table
    by_ansi = {r['ANSI']: r for r in rows if r['ANSI']}
    for k in range(1, 46):
        assert by_ansi[k]['Born & Wolf'] == T32_CODEV[k - 1], k
        if T32_FRINGE[k - 1] is not None:
            assert by_ansi[k]['Fringe'] == T32_FRINGE[k - 1], k


def test_the_printed_findings_hold(probe, table):
    _, text = table
    g = re.search(r'`ExtFringe` modes ([\d, ]+) \(', text)
    assert g, 'the ExtFringe note is printed'
    dead = [int(k) for k in g.group(1).split(',')]
    assert dead == [47, 48, 49, 58, 59, 60, 61, 62, 63, 64]
    for k in dead:
        _, _, s = probe.sag('ExtFringe', k)
        assert np.max(np.abs(s)) < 1e-9, f'ExtFringe {k} now applies a surface: regenerate Appendix E'
    assert '`NormHex` is refused at load' in text
    assert not probe.load('NormHex'), 'NormHex now loads: regenerate Appendix E'
