function art = run_compare(seg_in, opts)
%RUN_COMPARE  Compare stage runner: mmacos engine vs the linear model, per DOF.
%
%   art = run_compare(SEG_IN, 'hx', HX, 'jac', JAC, 'met', METMAT) is
%   the compare stage of the design pipeline
%       design -> segmentation -> sensitivities -> MET -> COMPARE -> simulate
%   (see design/runners/README.md).  It pokes each DOF of the linear
%   model IN TURN — first the rigid-body x DOFs of the sensed bodies
%   (default 100 nrad / 100 nm), then the z figure DOFs (segment-local
%   MonZernike modes), then the grid DOFs (per-segment influence
%   pokes) — and, for every poke, displays TWO graphics side by side:
%   one from the mmacos ENGINE, one from the LINEAR MODEL, each
%   showing the center-field OPD change on top of stacked bar charts
%   of the metrology beam lengths l and the edge-sensor readings by
%   axis (e_piston / e_gap / e_shear).  The z and grid DOFs do not
%   move l or e (met points and sensor points ride the rigid frames,
%   not the figure) — their bar charts stay in the movie, reading
%   zero, engine and model alike (Dave 2026-07-19).  Each poke stays
%   on screen for a settable dwell; every frame is saved and the
%   sequence is assembled into a GIF, alongside a per-poke agreement
%   report.
%
%   The linear model (Dave 2026-07-19, verbatim intent + the figure-
%   sensing extension of the same day):
%       w = dwdx*x + dwdz*z + dwdgrid*g + dwdu*u + w0
%       m = [l; e] = dmdx*x + dmdz*z + dmdgrid*g + m0
%   dmdz/dmdgrid are generated by macos.design.dmet_dfig (mode shape
%   evaluated at each sensor/launcher mount point, projected on the
%   measurement axis): the l rows and the e PISTON rows carry the
%   figure response; gap/shear rows vanish through the normal
%   projection.  The ENGINE's METcalc and the Hx keep met/sensor
%   points rigid, so for z/grid pokes the engine-side l/e bars read
%   zero while the LINEAR side shows the dmdz/dmdgrid prediction --
%   the movie displays that model-vs-engine gap explicitly, and the
%   blocks are exported for the simulator stage's estimator H.
%   The linear side of a poke is the matching Jacobian column times
%   the poke; the engine side is the same poke applied through the
%   SAME channel classes the sensitivity harvest used, with a retrace
%   (+ METcalc where the Rx carries met blocks).  u (the control) is
%   the SEGMENT + SM subset of x; the matching dwdx columns are
%   exported as dwdu for the simulator stage.
%
%   Engine-truth channels per poke:
%     w  channel apply (RigidBodyChannel / MonZernChannel /
%        GridChannel — the s4 harvest classes) -> trace(nElt-1) ->
%        OPD; delta vs the unperturbed baseline on the same mask.
%        Grid pokes run on the grid-augmented Rx of the harvest
%        (og.rx_path), with the influence basis REBUILT by the same
%        macos.segment_grid_basis call — a basis mismatch would fail
%        the agreement gate.
%     l  macos.met() (met points ride their element under the
%        programmatic perturb path); zero rows where the loaded Rx
%        declares no metrology (the grid-augmented Rx).
%     e  finite-rotation kinematics at the SegMirMaker sensor points
%        (Hx SensorPos): the sensor axis and moment arm ARE the
%        measurement model, so truth = axis . ((R(theta)-I)*rho +
%        delta) with the FULL rotation matrix — first order
%        reproduces the dedx row, the difference is the genuine
%        linearization error.  dedx is REBUILT from the Hx sidecar
%        (the met .mat copy is only cross-checked — a regenerated Hx
%        would otherwise poison the comparison).
%
%   REQUIRED OPTIONS:
%     'hx'    SegMirMaker Hx.m sidecar (axis/loc/SensorPos form)
%     'jac'   sensitivities .mat (s4_jacobians.mat: ox + optional
%             oz/og) or the dw_dx_multi 'ox' struct — must carry
%             per_field blocks
%     'met'   MET-stage .mat (run_met output) or an equivalent struct:
%             dldx (+ dldx_opt), bodies, seg, met_in / metopt_in
%   OPTIONS:
%     'channels'   subset of ["x" "z" "grid"] (default: every channel
%                  the jac provides, in that order — Dave 2026-07-19)
%     'met_rx'     Rx to poke for x/z (default: the met struct's
%                  metopt_in if present, else met_in; matching dldx)
%     'grid_rx'    Rx for the grid pokes (default: og.rx_path — the
%                  grid-augmented Rx the harvest used)
%     'poke_rot'   rotation poke, rad (default 1e-7 = 100 nrad)
%     'poke_trans' translation poke, m (default 1e-7 = 100 nm)
%     'poke_fig'   figure poke: MonZernike / influence amplitude
%                  (default 1e-7 = 100 nm surface)
%     'dofs'       x-DOF subset 1..6 = [Rx Ry Rz Tx Ty Tz] (default all)
%     'bodies'     x body subset (indices into the met bodies list,
%                  default all)
%     'control'    control-body indices for the dwdu export (default
%                  segments + hub — "segment and SM x", Dave)
%     'pm_ref_elt' segment_grid_basis footprint target for the grid
%                  basis rebuild (default 1 — the run_sensitivities
%                  default; must match the harvest)
%     'dwell'      seconds each poke stays on screen and per GIF frame
%                  (default 1.6 — Dave 2026-07-19, 0.25 read too fast)
%     'w_floor'    null-response floor, m (default 1e-12): pokes with
%                  no physical w (or l) response report rel = NaN
%                  ('null') instead of an FD-noise ratio
%     'gif'        assemble <name>_compare.gif (default true)
%     'ngridpts'   ray-grid override — MUST match the jac harvest
%                  sampling (default [] = keep the .in values)
%     'model_size' engine model (default 512)
%     'out_dir'    artifact directory (default: beside SEG_IN)
%     'name'       artifact basename (default: SEG_IN's basename)
%     'visible'    show the two figures live (default true; the movie
%                  IS the point — pass false in batch/tests)
%     'verbose'    (default true)
%
%   art: .table (per-poke agreement metrics, .chan = x|z|grid),
%        .frames_dir, .gif, .report, .mat, .dwdu, .u_cols, .worst.
%
%   See also: run_met, run_sensitivities, macos.design.edge_sensors,
%             macos.channels.RigidBodyChannel, macos.channels.
%             MonZernChannel, macos.channels.grid_channels.

arguments
    seg_in (1,1) string
    opts.hx (1,1) string
    opts.jac
    opts.met
    opts.channels (1,:) string = "auto"
    opts.met_rx (1,1) string = ""
    opts.grid_rx (1,1) string = ""
    opts.poke_rot (1,1) double {mustBePositive} = 1e-7
    opts.poke_trans (1,1) double {mustBePositive} = 1e-7
    opts.poke_fig (1,1) double {mustBePositive} = 1e-7
    opts.dofs (1,:) double {mustBeInteger, mustBeMember(opts.dofs, 1:6)} = 1:6
    opts.bodies double = []
    opts.control double = []
    opts.pm_ref_elt (1,1) double {mustBeInteger, mustBePositive} = 1
    opts.dwell (1,1) double {mustBeNonnegative} = 1.6
    opts.w_floor (1,1) double {mustBePositive} = 1e-12
    opts.gif (1,1) logical = true
    opts.ngridpts double = []
    opts.model_size (1,1) double = 512
    opts.out_dir (1,1) string = ""
    opts.name (1,1) string = ""
    opts.visible (1,1) logical = true
    opts.verbose (1,1) logical = true
end
assert(isfile(seg_in), 'run_compare: %s not found', seg_in);
assert(isfile(opts.hx), 'run_compare: Hx sidecar %s not found', opts.hx);
[ind, base] = fileparts(seg_in);
out_dir = opts.out_dir;  if strlength(out_dir) == 0, out_dir = ind; end
name = opts.name;        if strlength(name) == 0,   name = base; end
pth = @(suffix) char(fullfile(out_dir, name + suffix));
log_ = fopen(pth("_compare_report.txt"), 'w');
closer = onCleanup(@() fclose(log_));
if opts.verbose
    say = @(varargin) fprintf(1, varargin{:}) + fprintf(log_, varargin{:});
else
    say = @(varargin) fprintf(log_, varargin{:});
end
say('==== run_compare: %s ====\n', seg_in);

%% -- [0] ingest the upstream artifacts --------------------------------
M = met_struct_(opts.met);
seg = M.seg;  nseg = seg.nseg;  bodies = M.bodies;  nb = numel(bodies);
assert(isequal(bodies(1:nseg), seg.seg_elts), ...
    'run_compare: met bodies do not lead with the segment elements');
met_rx = opts.met_rx;
dldx = M.dldx;
if strlength(met_rx) == 0
    if isfield(M, 'metopt_in') && strlength(string(M.metopt_in)) > 0 ...
            && isfile(M.metopt_in)
        met_rx = string(M.metopt_in);
        if isfield(M, 'dldx_opt') && ~isempty(M.dldx_opt)
            dldx = M.dldx_opt;
        end
    else
        met_rx = string(M.met_in);
    end
end
assert(isfile(met_rx), 'run_compare: met Rx %s not found', met_rx);
nl = size(dldx, 1);
J = jac_all_(opts.jac);
ox = J.ox;
chansel = opts.channels;
if isscalar(chansel) && chansel == "auto"
    chansel = "x";
    if ~isempty(J.oz), chansel(end+1) = "z"; end
    if ~isempty(J.og), chansel(end+1) = "grid"; end
end
assert(~any(chansel == "z")    || ~isempty(J.oz), 'run_compare: jac has no dwdz output');
assert(~any(chansel == "grid") || ~isempty(J.og), 'run_compare: jac has no dwdgrid output');
% Convention match: the dwdx leg must share the per-field exit-pupil
% reset convention with the dwdz/dwdgrid legs it is joined with.  Mixing
% a frozen-EP dwdx (reset_xp=false) into a model whose dwdz/dwdgrid used
% reset_xp=true silently mixes tilt-reference conventions across channels
% (the family-asymmetry hazard the reset_xp addition closes).  The stamp
% is true | false | 'no-effect' -- 'no-effect' (FEX found no pupil to
% write, so the harvest is frozen-EP in practice) is EFFECTIVELY frozen,
% so it matches a false leg; only a genuine true-vs-false split is a
% mismatch.  reset_eff_() maps the tri-state stamp to that effective bool.
if isfield(ox, 'reset_xp')
    for leg = {J.oz, J.og}
        L = leg{1};
        if ~isempty(L) && isfield(L, 'reset_xp')
            assert(reset_eff_(ox.reset_xp) == reset_eff_(L.reset_xp), ...
                'run_compare:reset_xp_mismatch', ...
                ['dwdx reset_xp=%s but a dwdz/dwdgrid leg used reset_xp=%s' ...
                 ' -- regenerate the Jacobian with one convention'], ...
                reset_str_(ox.reset_xp), reset_str_(L.reset_xp));
        end
    end
end
icf = find(strcmp(ox.field_names, 'C'), 1);
assert(~isempty(icf), 'run_compare: jac has no center field ''C''');
% center-field dwdx block for the sensed bodies, [rot|trans] col order
[Bc, colmap, nochan] = dwdx_cols_(ox.per_field_dwdx{icf}, ...
    ox.channel_names, bodies);
W0j = ox.per_field_w_nom_2d{icf};
[~, jndx] = macos.m2v(W0j);
es = macos.design.edge_sensors(opts.hx);
assert(any(es.axis > 0), ['run_compare: legacy Hx (no MeasAxis/' ...
    'SensorPos) -- regenerate with the 2026-07-19 SegMirMaker']);
ie_p = find(es.axis == 1);  ie_g = find(es.axis == 2);
ie_s = find(es.axis == 3);
% dedx from the CURRENT Hx sidecar (readings BaseUnits -> SI: rot cols
% x cbm, translation cols dimensionless -- same construction as
% run_met).  The met .mat's copy is only cross-checked: if the Hx was
% regenerated after the MET stage ran, the stale rows would poison the
% comparison (caught 2026-07-19: the gap/shear axis-relabel left the
% s5 .mat one Hx generation behind).
dedx = zeros(es.nmeas, 6*nb);
dedx(:, 1:6*nseg) = es.dedx;                  % SI-scaled once cbm known
say(['[0] %d bodies (%d segments), channels [%s]; met Rx %s\n' ...
     '    jac: center field %d x %d x-cols; dedx %dx%d; dldx %dx%d\n'], ...
    nb, nseg, strjoin(chansel, ' '), met_rx, size(Bc, 1), size(Bc, 2), ...
    size(dedx), size(dldx));
if ~isempty(nochan)
    say(['    NOTE: no dwdx channels for element(s) %s (Reference/' ...
         'FocalPlane-class body):\n    linear w = 0 for their pokes ' ...
         '(engine response is null there too -- l/e still compared)\n'], ...
        num2str(nochan));
end

% x poke set
bsel = opts.bodies;  if isempty(bsel), bsel = 1:nb; end
control = opts.control;
if isempty(control), control = 1:min(nseg+1, nb); end   % segments + SM/hub
DOFN = {'Rx', 'Ry', 'Rz', 'Tx', 'Ty', 'Tz'};

%% -- [1] engine baseline ----------------------------------------------
old = cd(out_dir);  restore = onCleanup(@() cd(old));
m = macos.Session(opts.model_size);
m.load_rx(char(met_rx));
if ~isempty(opts.ngridpts), m.set_src_sampling(opts.ngridpts); end
cbm = m.cbm();
for s = 1:nseg
    dedx(:, (s-1)*6+(1:3)) = dedx(:, (s-1)*6+(1:3)) * cbm;
end
if isfield(M, 'dedx') && isequal(size(M.dedx), size(dedx)) ...
        && max(abs(dedx(:) - M.dedx(:))) > 1e-9 * max(abs(dedx(:)))
    warning('run_compare:stale_dedx', ...
        ['the met .mat''s dedx does not match the Hx sidecar -- the Hx ' ...
         'was regenerated after the MET stage ran; using the Hx (rerun ' ...
         'the MET stage to refresh its estimator products)']);
    say('    WARNING: met .mat dedx is STALE vs the Hx sidecar (using the Hx)\n');
end
wf_elt = m.num_elt() - 1;
m.trace(wf_elt);
Wb = m.opd();                                 % phase baseline (met Rx)
assert(isequal(size(Wb), size(W0j)), ['run_compare: engine OPD canvas ' ...
    '%dx%d vs jac %dx%d -- ngridpts must match the jac harvest'], ...
    size(Wb, 1), size(Wb, 2), size(W0j, 1), size(W0j, 2));
maskb = Wb ~= 0;
nover = nnz(maskb & (W0j == 0)) + nnz(~maskb & (W0j ~= 0));
l0 = macos.met();
assert(l0.n == nl, ...
    'run_compare: engine declares %d met beams, dldx has %d rows', l0.n, nl);
l0b = l0.l;
say('    baseline: %d OPD pixels (jac mask mismatch %d px), %d met beams, %d edge rows\n', ...
    nnz(maskb), nover, l0.n, es.nmeas);

%% -- [2] the poke loop: x, then z, then grid --------------------------
fdir = pth("_frames");
if ~exist(fdir, 'dir'), mkdir(fdir); end
gif_file = '';
if opts.gif, gif_file = pth("_compare.gif"); end
vis = 'off';  if opts.visible, vis = 'on'; end
fe = figure('Visible', vis, 'Position', [40 60 640 940], 'Color', 'w');
fl = figure('Visible', vis, 'Position', [700 60 640 940], 'Color', 'w');
fig_closer = onCleanup(@() close([fe fl]));
T = struct('chan', {}, 'label', {}, 'body', {}, 'dof', {}, 'poke', {}, ...
    'w_rms_t', {}, 'w_rel', {}, 'l_max_t', {}, 'l_rel', {}, ...
    'e_max_t', {}, 'e_rel', {}, 'l_max_m', {}, 'e_max_m', {});
ip = 0;

%% x: rigid-body DOFs of the sensed bodies
if any(chansel == "x")
    say('\n[2] x: rigid-body pokes (%g nrad rot / %g nm trans), %d bodies x %d DOFs:\n', ...
        opts.poke_rot*1e9, opts.poke_trans*1e9, numel(bsel), numel(opts.dofs));
    for kb = bsel(:).'
        for d = opts.dofs(:).'
            col = (kb-1)*6 + d;
            poke = opts.poke_trans;  utxt = 'nm';
            if d <= 3, poke = opts.poke_rot;  utxt = 'nrad'; end
            lbl = sprintf('%s %s %+g %s', body_name_(kb, nseg, bodies), ...
                          DOFN{d}, poke*1e9, utxt);
            ch = macos.channels.RigidBodyChannel(m, bodies(kb), d - 1);
            th = zeros(3, 1);  dl = zeros(3, 1);
            if d <= 3, th(d) = poke;  else, dl(d-3) = poke; end
            if kb <= nseg
                de_t = e_truth_(es, seg, cbm, kb, th, dl);
            else
                de_t = zeros(es.nmeas, 1);   % edge sensors live on segments
            end
            do_poke_('x', lbl, bodies(kb), d, ch, poke, ...
                col2map_(Bc(:, col)*poke, jndx), dldx(:, col)*poke, ...
                dedx(:, col)*poke, de_t);
        end
    end
end

%% z: segment-figure MonZernike DOFs.  The engine's METcalc holds met
%% points rigid and the Hx has no figure path, so the ENGINE l/e bars
%% read zero; the LINEAR bars show the dmdz model (figure motion at
%% each sensor/launcher mount point -- piston + l rows respond,
%% gap/shear vanish through the normal projection).
gmet = macos.met_geom();                      % on the loaded met Rx
dmz = [];  dmg = [];
if any(chansel == "z")
    oz = J.oz;
    icz = find(strcmp(oz.field_names, 'C'), 1);
    assert(~isempty(icz), 'run_compare: dwdz jac has no center field');
    Bz = oz.per_field_dwdz{icz};
    W0z = oz.per_field_w_nom_2d{icz};
    assert(isequal(size(W0z), size(Wb)), ...
        'run_compare: dwdz canvas %dx%d vs engine %dx%d', ...
        size(W0z, 1), size(W0z, 2), size(Wb, 1), size(Wb, 2));
    [~, jnz] = macos.m2v(W0z);
    dmz = macos.design.dmet_dfig(seg, es, gmet, ...
        'z_names', oz.channel_names, 'unit_to_m', cbm);
    say(['\n[2z] z: segment MonZernike pokes (%g nm figure), %d modes;\n' ...
         '     linear l/e = dmdz (dmet_dfig at the mount points) -- the\n' ...
         '     engine METcalc/Hx are RIGID, their bars read zero\n'], ...
        opts.poke_fig*1e9, numel(oz.channel_names));
    for k = 1:numel(oz.channel_names)
        tok = regexp(oz.channel_names{k}, ...
            '^Elt (\d+) MonZern(\d+)$', 'tokens', 'once');
        assert(~isempty(tok), ...
            'run_compare: unexpected dwdz channel ''%s'' (monzern expected)', ...
            oz.channel_names{k});
        elt = str2double(tok{1});  mode = str2double(tok{2});
        lbl = sprintf('%s Z%d %+g nm', seg_name_(elt, seg), mode, ...
                      opts.poke_fig*1e9);
        ch = macos.channels.MonZernChannel(m, elt, mode);
        % dwdz columns are OPD-BaseUnits per coef-BaseUnits (the dwdz/
        % dwdg supervisors apply NO cbm scale, unlike dwdx) -- x cbm
        % converts the prediction to SI to match the engine delta
        do_poke_('z', lbl, elt, mode, ch, opts.poke_fig, ...
            col2map_(Bz(:, k)*opts.poke_fig*cbm, jnz), ...
            dmz.dldz(:, k)*opts.poke_fig, dmz.dedz(:, k)*opts.poke_fig, ...
            zeros(es.nmeas, 1));
    end
end

%% grid: per-segment influence pokes on the grid-augmented Rx of the
%% harvest, with the basis REBUILT by the same segment_grid_basis call
if any(chansel == "grid")
    og = J.og;
    grx = opts.grid_rx;
    if strlength(grx) == 0, grx = string(og.rx_path); end
    assert(isfile(grx), ['run_compare: grid-augmented Rx %s not found ' ...
        '(og.rx_path; pass ''grid_rx'')'], grx);
    if isfield(og, 'sgb') && ~isempty(og.sgb)
        % the harvest's own basis (run_sensitivities persists it) --
        % the only bit-exact source; a rebuild can rotate the last
        % G-S mode (session-dependent tie-break, 2026-07-19)
        sgb = og.sgb;
        say('\n[2g] grid: influence pokes (%g nm) on %s (harvest basis og.sgb):\n', ...
            opts.poke_fig*1e9, grx);
    else
        warning('run_compare:sgb_rebuild', ...
            ['og carries no sgb -- rebuilding the influence basis; ' ...
             'the last G-S mode may be rotated vs the harvest ' ...
             '(re-harvest with the current run_sensitivities to persist it)']);
        say('\n[2g] grid: influence pokes (%g nm) on %s (basis REBUILT -- see warning):\n', ...
            opts.poke_fig*1e9, grx);
        sgb = macos.segment_grid_basis(m, char(grx), ...
            'pm_ref_elt', opts.pm_ref_elt, 'modes', og.zmodes, ...
            'orthogonalize', true);
    end
    dmg = macos.design.dmet_dfig(seg, es, gmet, ...
        'g_names', og.channel_names, 'sgb', sgb, 'unit_to_m', cbm);
    say(['     linear l/e = dmdgrid (dmet_dfig at the mount points; ' ...
         'engine bars rigid-zero)\n']);
    % segment_grid_basis traces (and ray-hist pokes) the Rx to measure
    % footprints -- RELOAD before the baseline, exactly as the
    % dw_dgrid_multi harvest does, or the leftover state biases every
    % grid FD at the ~20% level (caught 2026-07-19)
    m.load_rx(char(grx));
    if ~isempty(opts.ngridpts), m.set_src_sampling(opts.ngridpts); end
    gch = macos.channels.grid_channels(m, sgb);
    names_g = cellfun(@(c) c.name(), gch, 'UniformOutput', false);
    icg = find(strcmp(og.field_names, 'C'), 1);
    assert(~isempty(icg), 'run_compare: dwdgrid jac has no center field');
    Bg = og.per_field_dwdg{icg};
    W0g = og.per_field_w_nom_2d{icg};
    wf_elt = m.num_elt() - 1;                 % new engine context
    m.trace(wf_elt);
    Wb = m.opd();  maskb = Wb ~= 0;
    l0b = [];                                 % no met blocks on the grid Rx
    assert(isequal(size(W0g), size(Wb)), ...
        'run_compare: dwdgrid canvas %dx%d vs engine %dx%d', ...
        size(W0g, 1), size(W0g, 2), size(Wb, 1), size(Wb, 2));
    [~, jng] = macos.m2v(W0g);
    for k = 1:numel(og.channel_names)
        i = find(strcmp(names_g, og.channel_names{k}), 1);
        assert(~isempty(i), ['run_compare: rebuilt grid basis lacks ' ...
            'channel %s -- pm_ref_elt/modes mismatch with the harvest'], ...
            og.channel_names{k});
        tok = regexp(og.channel_names{k}, '^Elt (\d+) Grid(\d+)$', ...
            'tokens', 'once');
        elt = str2double(tok{1});  gk = str2double(tok{2});
        lbl = sprintf('%s G%d %+g nm', seg_name_(elt, seg), gk, ...
                      opts.poke_fig*1e9);
        do_poke_('grid', lbl, elt, gk, gch{i}, opts.poke_fig, ...
            col2map_(Bg(:, k)*opts.poke_fig*cbm, jng), ...   % BU/BU -> SI
            dmg.dldg(:, k)*opts.poke_fig, dmg.dedg(:, k)*opts.poke_fig, ...
            zeros(es.nmeas, 1));
    end
end
if isfile(fullfile(fdir, 'tmp_e.png'))
    delete(fullfile(fdir, 'tmp_e.png'), fullfile(fdir, 'tmp_l.png'));
end

%% -- [3] agreement summary + dwdu export ------------------------------
say('\n[3] worst engine-vs-linear agreement per channel:\n');
worst = struct();
for c = ["x", "z", "grid"]
    tc = T(strcmp({T.chan}, c));
    if isempty(tc), continue; end
    [wv, iw] = max([tc.w_rel]);
    lv = max([tc.l_rel]);  ev = max([tc.e_rel]);   % NaN-ignoring
    say('    %-5s (%3d pokes): w %8s (%s), l %8s, e %8s\n', c, numel(tc), ...
        rel_txt_(wv), tc(max(iw,1)).label, rel_txt_(lv), rel_txt_(ev));
    worst.(char(c)) = struct('w', wv, 'l', lv, 'e', ev);
end
