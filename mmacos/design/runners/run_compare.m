% ---- nested: one poke = engine truth + linear + metrics + graphics ----
    function do_poke_(chan, lbl, body, dof, ch, poke, dW_l, dl_l, de_l, de_t)
        ip = ip + 1;
        ch.apply(poke);
        m.trace(wf_elt);
        Wp = m.opd();
        if ~isempty(l0b)
            dl_t = macos.met().l - l0b;
        else
            dl_t = zeros(size(dl_l));
        end
        ch.restore();
        dW_t = nan(size(Wb));
        mk = maskb & (Wp ~= 0);
        dW_t(mk) = (Wp(mk) - Wb(mk)) * cbm;
        cm = isfinite(dW_t) & isfinite(dW_l);
        wt = dW_t(cm);  wl = dW_l(cm);
        r = struct('chan', chan, 'label', lbl, 'body', body, 'dof', dof, ...
            'poke', poke, ...
            'w_rms_t', rms_(wt), ...
            'w_rel', rms_(wt - wl) / max(rms_(wt), eps), ...
            'l_max_t', max(abs(dl_t)), ...
            'l_rel', max(abs(dl_t - dl_l)) / max(max(abs(dl_t)), eps), ...
            'e_max_t', max(abs(de_t)), ...
            'e_rel', max(abs(de_t - de_l)) / max(max(abs(de_t)), eps), ...
            'l_max_m', max(abs(dl_l)), 'e_max_m', max(abs(de_l)));
        if r.w_rms_t < opts.w_floor, r.w_rel = NaN; end  % null response
        if r.l_max_t < opts.w_floor, r.l_rel = NaN; end  % z/grid + quiet
        if r.e_max_t == 0,           r.e_rel = NaN; end  % hub/aft, z/grid
        T(end+1) = r;
        if strcmp(chan, 'x')
            say('    %-22s w %8.3g nm rms (rel %8s) | l %8.3g nm (rel %8s) | e %8.3g nm (rel %8s)\n', ...
                lbl, r.w_rms_t*1e9, rel_txt_(r.w_rel), r.l_max_t*1e9, ...
                rel_txt_(r.l_rel), r.e_max_t*1e9, rel_txt_(r.e_rel));
        else                              % figure DOF: engine l/e rigid-zero
            say('    %-22s w %8.3g nm rms (rel %8s) | l mdl %8.3g nm | e_pist mdl %8.3g nm\n', ...
                lbl, r.w_rms_t*1e9, rel_txt_(r.w_rel), ...
                r.l_max_m*1e9, r.e_max_m*1e9);
        end

        % the two graphics (shared color/axis limits so they read as a pair)
        cmax = max([abs(dW_t(cm)); abs(dW_l(cm)); eps]) * 1e9;
        yl = { bar_lim_(dl_t, dl_l), ...
               bar_lim_(de_t(ie_p), de_l(ie_p)), ...
               bar_lim_(de_t(ie_g), de_l(ie_g)), ...
               bar_lim_(de_t(ie_s), de_l(ie_s)) };
        draw_side_(fe, sprintf('mmacos ENGINE | %s', lbl), dW_t, ...
            dl_t, de_t(ie_p), de_t(ie_g), de_t(ie_s), cmax, yl);
        draw_side_(fl, sprintf('LINEAR MODEL | %s', lbl), dW_l, ...
            dl_l, de_l(ie_p), de_l(ie_g), de_l(ie_s), cmax, yl);
        drawnow;
        if opts.visible && opts.dwell > 0, pause(opts.dwell); end

        % save the pair as one combined frame (+ GIF)
        f1 = fullfile(fdir, 'tmp_e.png');  f2 = fullfile(fdir, 'tmp_l.png');
        print(fe, f1, '-dpng', '-r100');  print(fl, f2, '-dpng', '-r100');
        A = imread(f1);  B = imread(f2);
        h = max(size(A, 1), size(B, 1));
        A(end+1:h, :, :) = 255;  B(end+1:h, :, :) = 255;
        C = [A, B];
        fr = fullfile(fdir, sprintf('p%03d_%s.png', ip, ...
            regexprep(lbl, '[^\w+-]', '_')));
        imwrite(C, fr);
        if opts.gif
            [q, cmp] = rgb2ind(C, 256);
            if ip == 1
                imwrite(q, cmp, gif_file, 'gif', 'LoopCount', Inf, ...
                    'DelayTime', max(opts.dwell, 0.05));
            else
                imwrite(q, cmp, gif_file, 'gif', 'WriteMode', 'append', ...
                    'DelayTime', max(opts.dwell, 0.05));
            end
        end
    end
end

