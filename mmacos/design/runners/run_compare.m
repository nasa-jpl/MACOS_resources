function J = jac_all_(jac)
%JAC_ALL_  Accept the s4 .mat (ox + optional oz/og fields), a raw .mat
%   of dw_d*_multi outputs, or the ox struct itself.  ox is required
%   and must carry per-field blocks; oz/og enable the z/grid phases.
J = struct('ox', [], 'oz', [], 'og', []);
if isstruct(jac) && isfield(jac, 'ox')
    J.ox = jac.ox;
    if isfield(jac, 'oz'), J.oz = jac.oz; end
    if isfield(jac, 'og'), J.og = jac.og; end
elseif isstruct(jac) && isfield(jac, 'dwdxall')
    J.ox = jac;
else
    assert(isfile(jac), 'run_compare: jac .mat %s not found', jac);
    S = load(jac);
    if isfield(S, 'ox'), J.ox = S.ox; end
    if isfield(S, 'oz'), J.oz = S.oz; end
    if isfield(S, 'og'), J.og = S.og; end
    if isempty(J.ox)
        fn = fieldnames(S);
        for k = 1:numel(fn)
            v = S.(fn{k});
            if isstruct(v) && isfield(v, 'dwdxall') ...
                    && isfield(v, 'channel_names') ...
                    && any(~cellfun('isempty', regexp(v.channel_names, ...
                        '^Elt \d+ [RT][xyz]$', 'once')))
                J.ox = v;  break
            end
        end
    end
    assert(~isempty(J.ox), ...
        'run_compare: no dw_dx_multi rigid-body output in %s', jac);
end
for f = {'per_field_dwdx', 'per_field_w_nom_2d', 'field_names', 'dwdxall'}
    assert(isfield(J.ox, f{1}), ...
        'run_compare: jac lacks %s (re-harvest with the multi supervisor)', f{1});
end
if ~isempty(J.oz)
    assert(isfield(J.oz, 'per_field_dwdz'), ...
        'run_compare: oz lacks per_field_dwdz');
end
if ~isempty(J.og)
    assert(isfield(J.og, 'per_field_dwdg') && isfield(J.og, 'rx_path') ...
        && isfield(J.og, 'zmodes'), ...
        'run_compare: og lacks per_field_dwdg/rx_path/zmodes');
end
