function de = e_truth_(es, seg, cbm, s, th, dl)
%E_TRUTH_  Finite-rotation edge-sensor readings for a poke of segment S.
%   The sensor axis (recovered from the row's translation block -- the
%   measurement model itself) and the arm from the segment reference
%   point to the Hx SensorPos are exact; the rotation uses the full
%   Rodrigues matrix, so truth-vs-dedx differences are the genuine
%   linearization error.  th/dl in the segment triad, SI; de in SI.
de = zeros(es.nmeas, 1);
f = seg.frames(s);
Ts = [f.xhat, f.yhat, f.zhat];
thw = Ts * th;
R = rodrigues_(thw);
dlw = Ts * dl / cbm;                          % world, BaseUnits
for q = find(any(es.meas_to_seg == s, 1))
    blk = es.dedx(q, (s-1)*6 + (4:6)).';      % signed axis, triad comps
    a = Ts * blk;
    rho = es.sensor_pos(:, q) - f.rpt;
    de(q) = (a.' * ((R - eye(3))*rho + dlw)) * cbm;
end
end

function R = rodrigues_(w)
t = norm(w);
if t < 1e-300, R = eye(3); return; end
k = w / t;
K = [0 -k(3) k(2); k(3) 0 -k(1); -k(2) k(1) 0];
R = eye(3) + sin(t)*K + (1 - cos(t))*(K*K);
end

function [B, colmap, nochan] = dwdx_cols_(Bf, cn, bodies)
%DWDX_COLS_  Sensed bodies' 6-DOF columns in [rot|trans] order.  A body
%   with no channels in the harvest (Reference / FocalPlane-class --
%   e.g. an aft met ring riding the FPA) gets ZERO columns: the plain
%   engine trace has no wavefront response to it either, so zero IS
%   the matching linear model; its element id is returned in NOCHAN.
DOFN = {'Rx', 'Ry', 'Rz', 'Tx', 'Ty', 'Tz'};
nb = numel(bodies);
B = zeros(size(Bf, 1), 6*nb);
colmap = zeros(1, 6*nb);
nochan = [];
for b = 1:nb
    for d = 1:6
        i = find(strcmp(cn, sprintf('Elt %d %s', bodies(b), DOFN{d})), 1);
        if isempty(i)
            nochan(end+1) = bodies(b); %#ok<AGROW>
            break
        end
        B(:, (b-1)*6 + d) = Bf(:, i);
        colmap((b-1)*6 + d) = i;
    end
end
nochan = unique(nochan);
end

