function [T, act, wfs] = budget_spec_e5hex1()
%BUDGET_SPEC_E5HEX1  Example error-budget group table for e5hex1.
%   [T, ACT, WFS] = budget_spec_e5hex1() returns the group table T, one row
%   per budget line, grouped by element ROLE (PM segments, SM, lens,
%   detector) x rigid-body DOF type -- the canonical macos.budget schema
%   (authorable equally as this .m, a CSV, or an Excel sheet; see
%   macos.budget.read_spec) -- plus the WFC stage's noise inputs:
%     ACT  actuator noise per control group (run_budget 'act_sigma')
%     WFS  WFS noise per wavefront sample   (run_budget 'wfs_sigma')
%   Consumed by run_budget_e5hex1.m / run_budget.
%
%   Sigmas: the same illustrative alignment-class values per DOF type as
%   the v1 table (tilt 50 nrad, clocking 100 nrad, decenter 100 nm,
%   despace uniform +/-200 nm), split by role -- so the UNCONTROLLED total
%   is v1's to round-off (the coefficients are additive over columns).
%   Edit for a real budget.
%
%   Control set (Dave 2026-10-15): 6 DOF per PM segment + the SM's 6 DOF
%   (Control = 'WFC'); this deck has no DM / FCA.  Noise (Dave's ruling):
%     WFS       3 nm rms per wavefront sample (phase retrieval on image data)
%     actuator  1 nm per DOF; a ROTATION takes 1 nm of EDGE motion,
%               theta = 1 nm / r_edge, with r_edge the optic's edge radius:
%                 PM segment: hex vertex radius (width - gap)/sqrt(3)
%                             = (2666.667 - 50)/sqrt(3) = 1510.73 mm
%                             -> 0.66193 nrad
%                 SM:         ApVec radius 615 mm -> 1.62602 nrad
%               (clocking uses the same radius: the vertex moves r*theta).
%
%   Columns: Name Elements DOFs Modes Param Channel Dist Sigma Units
%            Min Max Cov Control.

seg = '1 2 3 4 5 6 7';
rows = { ...
  'PM Seg Tilt',     seg,  'tilt',     '', '', 'dwdx', 'normal',   50, 'nrad', NaN, NaN, 'iid', 'WFC'; ...
  'PM Seg Clocking', seg,  'clock',    '', '', 'dwdx', 'normal',  100, 'nrad', NaN, NaN, 'iid', 'WFC'; ...
  'PM Seg Decenter', seg,  'decenter', '', '', 'dwdx', 'normal',  100, 'nm',   NaN, NaN, 'iid', 'WFC'; ...
  'PM Seg Piston',   seg,  'despace',  '', '', 'dwdx', 'uniform', NaN, 'nm',  -200, 200, 'iid', 'WFC'; ...
  'SM Tilt',         '8',  'tilt',     '', '', 'dwdx', 'normal',   50, 'nrad', NaN, NaN, 'iid', 'WFC'; ...
  'SM Clocking',     '8',  'clock',    '', '', 'dwdx', 'normal',  100, 'nrad', NaN, NaN, 'iid', 'WFC'; ...
  'SM Decenter',     '8',  'decenter', '', '', 'dwdx', 'normal',  100, 'nm',   NaN, NaN, 'iid', 'WFC'; ...
  'SM Despace',      '8',  'despace',  '', '', 'dwdx', 'uniform', NaN, 'nm',  -200, 200, 'iid', 'WFC'; ...
  'Lens Tilt',       '9 10', 'tilt',     '', '', 'dwdx', 'normal',   50, 'nrad', NaN, NaN, 'iid', ''; ...
  'Lens Clocking',   '9 10', 'clock',    '', '', 'dwdx', 'normal',  100, 'nrad', NaN, NaN, 'iid', ''; ...
  'Lens Decenter',   '9 10', 'decenter', '', '', 'dwdx', 'normal',  100, 'nm',   NaN, NaN, 'iid', ''; ...
  'Lens Despace',    '9 10', 'despace',  '', '', 'dwdx', 'uniform', NaN, 'nm',  -200, 200, 'iid', ''; ...
  'FPA Tilt',        '13', 'tilt',     '', '', 'dwdx', 'normal',   50, 'nrad', NaN, NaN, 'iid', ''; ...
  'FPA Clocking',    '13', 'clock',    '', '', 'dwdx', 'normal',  100, 'nrad', NaN, NaN, 'iid', ''; ...
  'FPA Decenter',    '13', 'decenter', '', '', 'dwdx', 'normal',  100, 'nm',   NaN, NaN, 'iid', ''; ...
  'FPA Despace',     '13', 'despace',  '', '', 'dwdx', 'uniform', NaN, 'nm',  -200, 200, 'iid', ''};

T = cell2table(rows, 'VariableNames', {'Name','Elements','DOFs','Modes', ...
    'Param','Channel','Dist','Sigma','Units','Min','Max','Cov','Control'});

r_seg = (2666.666666666667 - 50) / sqrt(3) * 1e-3;   % m
r_sm  = 615e-3;                                       % m
e = 1e-9;                                             % 1 nm edge motion
act = { ...
  'PM Seg Tilt',     e / r_seg * 1e9, 'nrad'; ...
  'PM Seg Clocking', e / r_seg * 1e9, 'nrad'; ...
  'PM Seg Decenter', 1,               'nm';   ...
  'PM Seg Piston',   1,               'nm';   ...
  'SM Tilt',         e / r_sm * 1e9,  'nrad'; ...
  'SM Clocking',     e / r_sm * 1e9,  'nrad'; ...
  'SM Decenter',     1,               'nm';   ...
  'SM Despace',      1,               'nm'};
wfs = {3, 'nm'};
end
