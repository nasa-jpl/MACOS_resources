        use macos_api_mod, only: stop_info_set
        implicit none
        mwPointer plhs(*), prhs(*)
        integer nlhs, nrhs

        mwPointer mxGetPr, mxGetM, mxGetN
        mwPointer mxCreateDoubleMatrix, mxCreateDoubleScalar
        mwPointer pr
        integer*8 :: nbytes_tmp
        real(8)   :: dbuf(1)
        logical :: OK
        integer :: iElt
        real(8), allocatable :: VptOffset(:)
        integer :: i_tmp
        real(8), allocatable :: rbuf(:)

        IF (nrhs .ne. 3) CALL mexErrMsgTxt(
     &    'stop_info_set: expects 2 input arg(s)')

        pr = mxGetPr(prhs(2))
        CALL mxCopyPtrToReal8(pr, dbuf, int(1, kind=8))
        iElt = int(dbuf(1))
        allocate(VptOffset(2))
        nbytes_tmp = int(2, kind=8)
        pr = mxGetPr(prhs(3))
        CALL mxCopyPtrToReal8(pr, VptOffset, nbytes_tmp)

        CALL stop_info_set(OK, iElt, VptOffset)
        IF (.not. ok) THEN
          IF (allocated(VptOffset)) deallocate(VptOffset)
          CALL mexErrMsgTxt('mmacos: stop_info_set failed')
        END IF

        IF (allocated(VptOffset)) deallocate(VptOffset)
        end subroutine do_stop_info_set

